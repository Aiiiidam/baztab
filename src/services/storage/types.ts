import type { Readable } from 'node:stream';

/** Inclusive byte range, as in an HTTP Range header. */
export type ByteRange = { start: number; end: number };

export type ObjectRead = {
  body: Readable;
  /** Bytes in this response. */
  contentLength: number;
  /** Size of the whole object. */
  totalBytes: number;
};

export interface ObjectStorage {
  /** Store a local file under `key`. Overwrites an existing object. */
  put(key: string, filePath: string, bytes: number, contentType: string): Promise<void>;
  /** Read the whole object or one inclusive range; null when the object does not exist. */
  read(key: string, range?: ByteRange): Promise<ObjectRead | null>;
  /** Copy the object to a local file (worker scratch). False when it does not exist. */
  download(key: string, destination: string): Promise<boolean>;
  /** Size of the object, or null when it does not exist. */
  head(key: string): Promise<{ bytes: number } | null>;
  /** Delete the object. A missing object counts as deleted. */
  delete(key: string): Promise<void>;
  /** Totals for reconciliation against the ledger. */
  usage(): Promise<{ objects: number; bytes: number }>;
}

const KEY_PATTERN = /^[a-z0-9]+\/[a-z0-9]+\/original\.mp3$/;

/** Keys are generated by `objectKeyFor`; anything else is a programming error. */
export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid storage key');
}
